// pluginColor.ts — детерминированный цвет плагина (`--pc`) из его id.
//
// Единый источник идентичности плагина: палитра команд (palette.ts) и
// статусбар плагинов (pluginStatusBar.ts) берут цвет отсюда, чтобы один и тот
// же плагин везде выглядел одинаково (ADR-0025).

/**
 * Фиксированная палитра с гарантированным контрастом ≥4.5:1 на фонах приложения
 * (ADR-0024 §2.5). Каждый цвет проверен на --bg-0 (#111318) и --bg-1 (#161920).
 */
const PALETTE = [
  "hsl(262 65% 70%)", // фиолетовый
  "hsl(217 65% 65%)", // синий
  "hsl(160 65% 55%)", // бирюзовый
  "hsl(330 65% 65%)", // розовый
  "hsl(25 65% 65%)",  // оранжевый
  "hsl(120 65% 55%)", // зелёный
] as const;

/** Стабильный цвет плагина: детерминированный выбор из палитры по `plugin_id`. */
export function pluginColor(id: string): string {
  let hash = 0;
  for (let i = 0; i < id.length; i++) hash = (hash * 31 + id.charCodeAt(i)) >>> 0;
  return PALETTE[hash % PALETTE.length];
}
