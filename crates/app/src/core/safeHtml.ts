const FORBIDDEN_TAGS = /<\s*(script|iframe|object|embed)/i;

/** РРЅР»Р°Р№РЅ-РѕР±СЂР°Р±РѕС‚С‡РёРєРё (`onclick=` Рё С‚.Рї.) вЂ” РІРЅРµ allowlist Р°С‚СЂРёР±СѓС‚РѕРІ `md-core`. */
