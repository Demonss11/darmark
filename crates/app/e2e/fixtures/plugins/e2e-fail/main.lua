-- E2E-фикстура плагина, падающего при активации (проверка карантина, S13).
--
-- on_activate намеренно бросает ошибку: хост трактует это как неудачный запуск и
-- копит серию карантина (QUARANTINE_THRESHOLD = 3). После трёх неудач подряд плагин
-- автоотключается; ручное включение тумблером сбрасывает карантин, но сам плагин
-- по-прежнему падает — статус возвращается к «ошибка», а не к «карантин».
function on_activate(_ctx)
  error("e2e-fail: намеренная ошибка активации")
end
